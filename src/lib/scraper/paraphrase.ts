const MAX_BODY_IMAGES = 5;

const PARAPHRASE_SYSTEM_PROMPT =
  "Kamu adalah redaktur senior di Lensaplus (media berita digital nasional Indonesia). " +
  "Tugasmu memahami konsep/inti berita dari naskah sumber, menerjemahkan langsung bila sumber berbahasa asing, lalu menuliskannya ulang dari nol menjadi berita Bahasa Indonesia yang orisinal, lugas sesuai PUEBI/EYD, akurat pada fakta, dan tidak menjiplak kalimat sumber. " +
  "Jawab HANYA dalam format JSON valid tanpa markdown code fence dan tanpa teks tambahan di luar JSON.";

/**
 * Pull every `<img>` URL from the source body in document order, dedup,
 * resolve relative URLs against `baseUrl`, and skip the hero image so we
 * don't duplicate what's already used as featuredImage.
 */
function extractBodyImageUrls(
  html: string,
  baseUrl: string,
  excludeHeroUrl?: string,
): string[] {
  const $ = cheerio.load(html);
  const seen = new Set<string>();
  const out: string[] = [];
  $("img").each((_, el) => {
    const $img = $(el) as cheerio.Cheerio<DomElement>;
    const raw = pickImageSrc($img, $);
    if (!raw) return;
    let abs: string;
    try {
      abs = new URL(raw, baseUrl).toString();
    } catch {
      return;
    }
    if (!/^https?:\/\//i.test(abs)) return;
    if (excludeHeroUrl && abs === excludeHeroUrl) return;
    if (!looksLikeContentImageUrl(abs)) return;
    if (seen.has(abs)) return;
    seen.add(abs);
    out.push(abs);
  });
  return out.slice(0, MAX_BODY_IMAGES);
}

/**
 * Inject `<figure><img/></figure>` markers into the AI-paraphrased body
 * at evenly-spaced paragraph boundaries. We split on `</p>` so images
 * always land between full paragraphs, never inside one.
 *
 * Layout: image #1 lands after the first paragraph (right under the
 * lead), the rest are spaced through the body.
 */
export function injectImagesIntoBody(
  bodyHtml: string,
  imageUrls: string[],
  altText: string,
  sourceName?: string,
): string {
  if (imageUrls.length === 0) return bodyHtml;

  const captionHtml = sourceName
    ? `<figcaption class="text-xs text-txt-muted mt-1.5 text-center">Foto: ${escapeAttr(sourceName)}</figcaption>`
    : "";

  // Split on closing </p> so we keep paragraph integrity.
  const parts = bodyHtml.split(/(<\/p>)/i);
  const paragraphCloses: number[] = [];
  parts.forEach((seg, i) => {
    if (/<\/p>/i.test(seg)) paragraphCloses.push(i);
  });

  if (paragraphCloses.length === 0) {
    // Fallback: just append figures at the end.
    const figures = imageUrls
      .map(
        (url) =>
          `<figure><img src="${url}" alt="${escapeAttr(altText)}" />${captionHtml}</figure>`,
      )
      .join("\n");
    return `${bodyHtml}\n${figures}`;
  }

  // Always place image #0 right after the first paragraph (lead), then spread
  // any remaining images (slice(1)) across subsequent paragraphs without duplicating #0.
  const insertSet = new Map<number, string>();
  const makeFigure = (url: string) =>
    `<figure><img src="${url}" alt="${escapeAttr(altText)}" />${captionHtml}</figure>`;

  const remaining = imageUrls.slice(1);
  const remainingCloses = paragraphCloses.slice(1);

  if (remainingCloses.length === 0) {
    insertSet.set(paragraphCloses[0], imageUrls.map(makeFigure).join("\n"));
  } else {
    insertSet.set(paragraphCloses[0], makeFigure(imageUrls[0]));
    const N = remainingCloses.length;
    const M = Math.min(remaining.length, N);
    for (let k = 0; k < M; k++) {
      const pos = M === N ? k : Math.floor(((k + 1) * N) / (M + 1));
      const closeIdx = remainingCloses[Math.min(N - 1, pos)];
      if (!insertSet.has(closeIdx)) {
        insertSet.set(closeIdx, makeFigure(remaining[k]));
      }
    }
  }

  // Re-assemble.
  const rebuilt: string[] = [];
  parts.forEach((seg, i) => {
    rebuilt.push(seg);
    if (insertSet.has(i)) rebuilt.push(insertSet.get(i)!);
  });
  return rebuilt.join("");
}

function escapeAttr(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

interface AiParaphrase {
  title: string;
  excerpt: string;
  content: string;
  suggestedTags: string[];
}

function stripCodeFence(raw: string): string {
  const trimmed = raw.trim();
  const fenced = trimmed.match(/^```(?:json)?\s*\n?([\s\S]*?)\n?```$/);
  if (fenced) return fenced[1].trim();
  return trimmed;
}

function tryParseAi(raw: string): AiParaphrase | null {
  const tryParseJson = (candidate: string): Record<string, unknown> | null => {
    try {
      const parsed = JSON.parse(candidate);
      if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) {
        return parsed as Record<string, unknown>;
      }
    } catch {
      /* fall through */
    }
    return null;
  };

  const cleaned = stripCodeFence(raw);
  let parsed = tryParseJson(cleaned);
  if (!parsed) {
    const objMatch = cleaned.match(/\{[\s\S]*\}/);
    if (objMatch) parsed = tryParseJson(objMatch[0]);
  }
  if (
    parsed &&
    typeof parsed.title === "string" &&
    typeof parsed.content === "string"
  ) {
    const cleanedTitle = cleanAIShortText(parsed.title) || parsed.title.trim();
    const cleanedExcerpt =
      typeof parsed.excerpt === "string"
        ? cleanAIShortText(parsed.excerpt) || parsed.excerpt.trim()
        : "";
    const cleanedContent = cleanAILongText(parsed.content) || parsed.content.trim();
    const plainContent = cleanedContent.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
    if (!cleanedTitle || !cleanedContent || !plainContent) {
      return null;
    }
    return {
      title: cleanedTitle,
      excerpt: cleanedExcerpt,
      content: cleanedContent,
      suggestedTags: Array.isArray(parsed.suggestedTags)
        ? parsed.suggestedTags
            .filter((t: unknown): t is string => typeof t === "string")
            .slice(0, 8)
        : [],
    };
  }
  return null;
}

function isSlugUniqueConstraintError(err: unknown): boolean {
  if (!err || typeof err !== "object") return false;
  const e = err as { code?: string; meta?: { target?: unknown } };
  if (e.code !== "P2002") return false;
  if (Array.isArray(e.meta?.target)) {
    return e.meta.target.includes("slug");
  }
  return true;
}

async function uniqueSlug(base: string): Promise<string> {
  const root = slugify(base).slice(0, 90) || "artikel";
  const existing = await prisma.article.findUnique({
    where: { slug: root },
    select: { id: true },
  });
  if (!existing) return root;
  const suffix = Math.random().toString(36).slice(2, 8);
  return `${root}-${suffix}`;
}

export interface ParaphraseInput {
  /** The scraped upstream article. */
  source: ScrapedArticle;
  /** Display name of the source (e.g. "Bank BJB"). */
  sourceName: string;
  /** Owner of the resulting draft. */
  authorId: string;
  authorName: string;
  /** Category the draft will land in. */
  categoryId: string;
  /** Default tags from the NewsSource. */
  defaultTags?: string[];
  /** Optional thumbnail URL captured from the listing card as a fallback hero. */
  listingThumbnail?: string;
  /** Whether to download the hero image. Default true. */
  downloadImage?: boolean;
  /** Whether to publish the resulting article immediately instead of saving as DRAFT. Default false. */
  autoPublish?: boolean;
}

export interface ParaphraseResult {
  articleId: string;
  slug: string;
  title: string;
  /** Resulting article status ("DRAFT" or "PUBLISHED"). */
  status: "DRAFT" | "PUBLISHED";
  /** Tokens reported by callAI(). */
  tokens: number;
  /** AI provider used. */
  provider: string;
  /** Local URL of the downloaded hero image, if any. */
  featuredImage?: string;
  /** Detected language of the upstream source. */
  sourceLang?: string;
}

export async function paraphraseAndCreateDraft(
  input: ParaphraseInput,
): Promise<ParaphraseResult> {
  const { source, sourceName, authorId, categoryId, defaultTags = [] } = input;
  const downloadImage = input.downloadImage ?? true;

  // Photo credit = the real publisher derived from the upstream URL's domain
  // (e.g. https://www.bola.com/... → "Bola"), NOT the configured source name —
  // editors sometimes name a source "Lensaplus", which wrongly credited our
  // own site as the photo source. Falls back to sourceName if the URL can't
  // be parsed into a brand.
  const rawCredit = sourceLabelFromUrl(source.url) ?? sourceName;
  const creditLabel = formatSourceWithWebsite(rawCredit, source.url);

  const plainSourceText = source.contentHtml
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const detectedLang =
    source.lang || detectLanguage(`${source.title} ${plainSourceText}`);
  const foreignSource = isForeignLanguage(detectedLang);
  const langLabel = languageLabelId(detectedLang);

  const langInstruction = foreignSource
    ? `TERJEMAHAN OTOMATIS KE BAHASA INDONESIA (WAJIB): Sumber berita ini terdeteksi berbahasa ${langLabel}. ` +
      `TERJEMAHKAN LANGSUNG seluruh komponen — judul, ringkasan, seluruh isi artikel, kutipan langsung narasumber, istilah, dan tag — ke dalam Bahasa Indonesia jurnalistik yang alami, mengalir, dan sesuai PUEBI/EYD. Jangan menyisakan kalimat berbahasa asing.`
    : detectedLang === "id"
      ? `BAHASA OUTPUT: Tetap dalam Bahasa Indonesia jurnalistik sesuai PUEBI/EYD dengan susunan kalimat yang sepenuhnya baru.`
      : `DETEKSI & TERJEMAHAN BAHASA (WAJIB): Periksa bahasa teks sumber terlebih dahulu. Bila sumber BUKAN Bahasa Indonesia, terjemahkan langsung seluruh komponen (judul, ringkasan, isi, kutipan narasumber, dan tag) ke Bahasa Indonesia jurnalistik yang alami sekaligus parafrase; bila sudah Bahasa Indonesia, parafrase ulang sepenuhnya.`;

  const userPrompt = `Anda menuliskan ulang berita dari sumber eksternal untuk Lensaplus dengan metode PARAFRASE BERBASIS KONSEP (bukan sekadar mengganti sinonim kata per kata).

${langInstruction}

METODE PARAFRASE KONSEP & ATURAN JURNALISTIK:
1. Serap konsep inti berita (5W+1H, sebab-akibat, konteks kebijakan/bisnis/peristiwa, dan dampaknya), lalu bangun ulang alur cerita sepenuhnya memakai struktur piramida terbalik redaksi Lensaplus.
2. DILARANG menjiplak struktur kalimat sumber atau menerjemahkan secara kaku kata per kata. Ubah struktur kalimat, urutan penyajian, serta transisi antarparagraf.
3. JANGAN menambah klaim spesifik, angka palsu, atau kutipan fiktif yang tidak ada pada sumber.
4. Pertahankan SEMUA fakta penting: angka, tanggal, nama tokoh, jabatan, nama lembaga/perusahaan, lokasi, dan inti kutipan langsung secara akurat (untuk sumber berbahasa asing, terjemahkan isi kutipan ke Bahasa Indonesia dengan makna persis).
5. Lead paragraf pertama wajib kuat dan langsung menjawab unsur utama 5W+1H.
6. PANJANG ARTIKEL WAJIB MINIMAL 380–650 KATA (wajib di atas ${MIN_PUBLISH_WORDS + 30} kata agar memenuhi syarat publikasi minimal ${MIN_PUBLISH_WORDS} kata). Jika naskah sumber pendek, perkaya secara faktual dan edukatif dengan menjabarkan latar belakang topik/instansi terkait, konteks industri/regulasi umum yang relevan, penjelasan istilah penting, serta implikasi/manfaat informasi tersebut bagi masyarakat/pembaca.
7. Format body HTML bersih dan nyaman dibaca: <p> untuk paragraf pendek, <h2> untuk sub-judul tematik (1–3 sub-judul), <blockquote> untuk kutipan penting, <ul>/<li> dan <strong> seperlunya.

JUDUL SUMBER: "${source.title}"

ISI SUMBER (${source.wordCount} kata):
"""
${plainSourceText.slice(0, 6_000)}
"""

Format output WAJIB JSON valid dalam Bahasa Indonesia untuk SEMUA field (tanpa teks lain di luar JSON):
{
  "title": "judul berita Bahasa Indonesia yang segar, informatif, dan lugas (50-85 karakter, hindari clickbait)",
  "excerpt": "ringkasan Bahasa Indonesia 130-160 karakter",
  "content": "body artikel HTML Bahasa Indonesia lengkap hasil parafrase konsep (minimal 380 kata)",
  "suggestedTags": ["tag1 indonesia", "tag2", "tag3", "tag4", "tag5"]
}`;

  const ai = await callAI({
    feature: "article_draft",
    systemPrompt: PARAPHRASE_SYSTEM_PROMPT,
    userPrompt,
    maxTokens: 2_800,
    temperature: 0.65,
    allowCombo: true,
    userId: authorId,
    articleTitle: source.title,
  });

  const parsed = tryParseAi(ai.text);
  if (!parsed) {
    throw new Error(
      `AI did not return parseable JSON for ${source.url}. First 200 chars: ${ai.text.slice(0, 200)}`,
    );
  }

  let totalTokens = ai.totalTokens;
  const currentWords = countContentWords(parsed.content);
  if (currentWords > 0 && currentWords < MIN_PUBLISH_WORDS + 20) {
    const neededWords = Math.max(150, MIN_PUBLISH_WORDS + 60 - currentWords);
    try {
      const expandRes = await callAI({
        feature: "article_draft",
        systemPrompt:
          "Kamu adalah redaktur senior Lensaplus. Tugasmu memperdalam artikel berita yang masih terlalu pendek dengan menambahkan 2–3 paragraf konteks latar belakang, penjelasan istilah/regulasi umum terkait, dan implikasi bagi masyarakat/pembaca dalam Bahasa Indonesia jurnalistik (PUEBI/EYD). Jangan mengarang angka atau kutipan fiktif. Jawab HANYA dengan blok HTML (<h2> dan <p>) tanpa markdown code fence dan tanpa mengulang paragraf yang sudah ada.",
        userPrompt:
          `JUDUL ARTIKEL: "${parsed.title}"\n\n` +
          `ISI ARTIKEL SAAT INI (${currentWords} kata, butuh tambahan ±${neededWords} kata agar minimal di atas ${MIN_PUBLISH_WORDS} kata):\n` +
          `${parsed.content}\n\n` +
          `Tambahkan sub-judul <h2> yang relevan beserta 2–3 paragraf pendalaman konteks dan implikasi (±${neededWords}–240 kata) yang menyambung secara alami di bagian akhir artikel.`,
        maxTokens: 1_200,
        temperature: 0.6,
        userId: authorId,
        articleTitle: parsed.title,
      });
      if (expandRes && typeof expandRes.text === "string" && expandRes.text.trim()) {
        const cleanedExtra = cleanAILongText(
          stripCodeFence(expandRes.text),
        ).trim();
        if (cleanedExtra.length >= 80) {
          parsed.content = `${parsed.content}\n${cleanedExtra}`;
          totalTokens += expandRes.totalTokens || 0;
        }
      }
    } catch {
      /* best-effort expansion: keep initial paraphrase if expansion fails */
    }
  }

  // Image: download hero (trying candidates in priority order) + body images to /uploads.
  const heroCandidateUrls = Array.from(
    new Set(
      [
        ...(source.heroImageCandidates ??
          (source.heroImageUrl ? [source.heroImageUrl] : [])),
        ...(input.listingThumbnail ? [input.listingThumbnail] : []),
      ].filter((u) => /^https?:\/\//i.test(u)),
    ),
  );

  let featuredImage: string | undefined;
  let downloadedHeroUpstreamUrl: string | undefined;

  if (downloadImage && heroCandidateUrls.length > 0) {
    for (const candidateUrl of heroCandidateUrls) {
      try {
        const dl = await downloadImageToUploads(candidateUrl, {
          title: parsed.title.slice(0, 200),
          caption: parsed.excerpt || source.excerpt,
          credit: creditLabel,
          referer: source.url,
          uploadedBy: authorId,
          uploaderName: input.authorName,
        });
        featuredImage = dl.url;
        downloadedHeroUpstreamUrl = candidateUrl;
        break;
      } catch (err) {
        console.warn(
          `[scraper] hero image download failed (${candidateUrl}):`,
          err instanceof Error ? err.message : String(err),
        );
      }
    }
  } else if (heroCandidateUrls.length > 0) {
    featuredImage = heroCandidateUrls[0];
    downloadedHeroUpstreamUrl = heroCandidateUrls[0];
  }

  // Pull body images from pre-sanitized extraction (preserves lazy data-src/srcset)
  // falling back to contentHtml, excluding whichever URL became the hero image.
  const localBodyImageUrls: string[] = [];
  if (downloadImage) {
    const rawCandidates =
      source.bodyImageUrls && source.bodyImageUrls.length > 0
        ? source.bodyImageUrls
        : extractBodyImageUrls(source.contentHtml, source.url);
    const upstreamBodyImageUrls = rawCandidates
      .filter((u) => !downloadedHeroUpstreamUrl || u !== downloadedHeroUpstreamUrl)
      .slice(0, MAX_BODY_IMAGES);

    for (const upstreamUrl of upstreamBodyImageUrls) {
      try {
        const dl = await downloadImageToUploads(upstreamUrl, {
          title: parsed.title.slice(0, 200),
          caption: parsed.excerpt || source.excerpt,
          credit: creditLabel,
          referer: source.url,
          uploadedBy: authorId,
          uploaderName: input.authorName,
        });
        localBodyImageUrls.push(dl.url);
      } catch (err) {
        console.warn(
          `[scraper] body image download failed (${upstreamUrl}):`,
          err instanceof Error ? err.message : String(err),
        );
      }
    }

    // Last-resort hero promotion: if all hero candidates failed, promote first body image.
    if (!featuredImage && localBodyImageUrls.length > 0) {
      featuredImage = localBodyImageUrls.shift();
    }
  }

  const bodyWithImages = injectImagesIntoBody(
    stripAttributionFooter(parsed.content),
    localBodyImageUrls,
    parsed.title,
    creditLabel,
  );
  const finalContent = sanitizeHtml(bodyWithImages);

  const slug = await uniqueSlug(parsed.title);

  // Tags: prioritise configured source defaults first, then AI suggestions (capped 8).
  const seenTagSlugs = new Set<string>();
  const allTagNames: string[] = [];
  for (const rawTag of [...defaultTags, ...parsed.suggestedTags]) {
    if (typeof rawTag !== "string") continue;
    const trimmed = rawTag.trim().slice(0, 40);
    if (!trimmed) continue;
    const slug = slugify(trimmed);
    if (!slug || seenTagSlugs.has(slug)) continue;
    seenTagSlugs.add(slug);
    allTagNames.push(trimmed);
    if (allTagNames.length >= 8) break;
  }

  // Safely resolve/create tag IDs without P2002 race collisions
  const resolvedTagIds = await resolveTagIds(allTagNames);
  const tagConnections = resolvedTagIds.map((id) => ({ id }));

  const contentExcerptFallback = parsed.content
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 160);
  const resolvedExcerpt =
    parsed.excerpt.slice(0, 500) ||
    contentExcerptFallback ||
    (!foreignSource ? source.excerpt.slice(0, 500) : "") ||
    null;

  const guardrail = checkArticle(
    finalContent,
    `${source.title}\n${plainSourceText}`,
  );
  const guardrailNote =
    guardrail.warnings.length > 0
      ? `[Guardrail] ${guardrail.warnings.map((w) => w.detail).join(" | ").slice(0, 800)}`
      : null;

  const shouldPublish = Boolean(input.autoPublish);
  const quality = shouldPublish
    ? checkArticleQuality(finalContent, featuredImage)
    : null;
  const willPublish = shouldPublish && Boolean(quality?.ok) && guardrail.pass;
  if (shouldPublish && !willPublish) {
    const reason = !quality?.ok
      ? (quality?.reason ?? "quality check failed")
      : `guardrail failed (${guardrail.warnings.length} warning(s))`;
    console.warn(
      `[scraper] autoPublish downgraded to DRAFT (${source.url}): ${reason}`,
    );
  }
  const targetStatus: "DRAFT" | "PUBLISHED" = willPublish ? "PUBLISHED" : "DRAFT";
  const cleanTitle = parsed.title.slice(0, 250);
  const seoTitle =
    cleanTitle.length <= 50
      ? `${cleanTitle} | Lensaplus`
      : `${cleanTitle.slice(0, 57).replace(/\s+\S*$/, "")}...`;
  const seoDescription = (resolvedExcerpt || contentExcerptFallback).slice(0, 155) || null;
  const readTime = calculateReadTime(finalContent);

  const rootSlug = slugify(parsed.title).slice(0, 90) || "artikel";
  let candidateSlug = slug;
  let article: { id: string; slug: string; title: string } | null = null;
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      article = await prisma.article.create({
        data: {
          title: cleanTitle,
          slug: candidateSlug,
          content: finalContent,
          excerpt: resolvedExcerpt,
          status: targetStatus,
          publishedAt: willPublish ? new Date() : null,
          readTime,
          seoTitle,
          seoDescription,
          isAutoGenerated: true,
          origin: "SCRAPER",
          sourceArticleId: null,
          ...(guardrailNote ? { reviewNote: guardrailNote } : {}),
          featuredImage: featuredImage || null,
          authorId,
          categoryId,
          tags:
            tagConnections.length > 0 ? { connect: tagConnections } : undefined,
          sources: {
            create: [
              {
                name: creditLabel,
                url: source.url,
              },
            ],
          },
        },
        select: { id: true, slug: true, title: true },
      });
      break;
    } catch (err) {
      if (isSlugUniqueConstraintError(err) && attempt < 4) {
        candidateSlug = `${rootSlug}-${Math.random().toString(36).slice(2, 8)}`;
        continue;
      }
      throw err;
    }
  }
  if (!article) {
    throw new Error(`Failed to create article after slug collision retries for ${source.url}`);
  }

  enqueueSorotanGeneration(article.id);
  if (willPublish) {
    void import("@/lib/seo-auto")
      .then(({ onArticlePublished }) => onArticlePublished(article.slug, article.id))
      .catch((err) => {
        console.warn(
          "[scraper] onArticlePublished failed:",
          err instanceof Error ? err.message : String(err),
        );
      });
  }

  return {
    articleId: article.id,
    slug: article.slug,
    title: article.title,
    status: targetStatus,
    tokens: totalTokens,
    provider: ai.provider,
    featuredImage,
    sourceLang: detectedLang,
  };
}
