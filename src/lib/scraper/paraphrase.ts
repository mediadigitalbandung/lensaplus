/**
 * Paraphrase a single ScrapedArticle into a Lensaplus DRAFT article.
 *
 * Strict 1:1: one source URL → one draft. The cron's listing pass walks
 * candidates and calls this for the first one not already in
 * `NewsSource.scrapedUrls`.
 *
 * Pipeline:
 *   1. AI paraphrase (callAI feature="article_draft"). When the source
 *      is English, the prompt asks for a Bahasa Indonesia translation
 *      + paraphrase in one pass.
 *   2. Resolve fields: title / excerpt / content / tags from AI output.
 *   3. Download hero image to /uploads (registered in Media library).
 *   4. Append a "Disarikan dari …" attribution footer.
 *   5. Insert Article row with status=DRAFT, isAutoGenerated=true,
 *      sourceArticleId remains null (source is external — we just
 *      record it in the audit log + content footer).
 */

import * as cheerio from "cheerio";
import type { Element as DomElement } from "domhandler";
import { prisma } from "@/lib/prisma";
import { callAI } from "@/lib/ai-client";
import { sanitizeHtml, cleanAIShortText, cleanAILongText } from "@/lib/sanitize";
import { resolveTagIds } from "@/lib/resolve-tags";
import { slugify } from "@/lib/utils";
import { enqueueSorotanGeneration } from "@/lib/seo/sorotan-generator";
import { downloadImageToUploads } from "./download-image";
import { pickImageSrc, looksLikeContentImageUrl } from "./html-utils";
import { sourceLabelFromUrl } from "./source-label";
import type { ScrapedArticle } from "./types";

const MAX_BODY_IMAGES = 5;

/**
 * Pull every `<img>` URL from the source body in document order, dedup,
 * resolve relative URLs against `baseUrl`, and skip the hero image so we
 * don't duplicate what's already used as featuredImage.
 */
function extractBodyImageUrls(
  html: string,
  baseUrl: string,
  excludeHeroUrl?: string,
): string[] {
  const $ = cheerio.load(html);
  const seen = new Set<string>();
  const out: string[] = [];
  $("img").each((_, el) => {
    const $img = $(el) as cheerio.Cheerio<DomElement>;
    const raw = pickImageSrc($img, $);
    if (!raw) return;
    let abs: string;
    try {
      abs = new URL(raw, baseUrl).toString();
    } catch {
      return;
    }
    if (!/^https?:\/\//i.test(abs)) return;
    if (excludeHeroUrl && abs === excludeHeroUrl) return;
    if (!looksLikeContentImageUrl(abs)) return;
    if (seen.has(abs)) return;
    seen.add(abs);
    out.push(abs);
  });
  return out.slice(0, MAX_BODY_IMAGES);
}

/**
 * Inject `<figure><img/></figure>` markers into the AI-paraphrased body
 * at evenly-spaced paragraph boundaries. We split on `</p>` so images
 * always land between full paragraphs, never inside one.
 *
 * Layout: image #1 lands after the first paragraph (right under the
 * lead), the rest are spaced through the body.
 */
export function injectImagesIntoBody(
  bodyHtml: string,
  imageUrls: string[],
  altText: string,
  sourceName?: string,
): string {
  if (imageUrls.length === 0) return bodyHtml;

  const captionHtml = sourceName
    ? `<figcaption class="text-xs text-txt-muted mt-1.5 text-center">Foto: ${escapeAttr(sourceName)}</figcaption>`
    : "";

  // Split on closing </p> so we keep paragraph integrity.
  const parts = bodyHtml.split(/(<\/p>)/i);
  const paragraphCloses: number[] = [];
  parts.forEach((seg, i) => {
    if (/<\/p>/i.test(seg)) paragraphCloses.push(i);
  });

  if (paragraphCloses.length === 0) {
    // Fallback: just append figures at the end.
    const figures = imageUrls
      .map(
        (url) =>
          `<figure><img src="${url}" alt="${escapeAttr(altText)}" />${captionHtml}</figure>`,
      )
      .join("\n");
    return `${bodyHtml}\n${figures}`;
  }

  // Always place image #0 right after the first paragraph (lead), then spread
  // any remaining images (slice(1)) across subsequent paragraphs without duplicating #0.
  const insertSet = new Map<number, string>();
  const makeFigure = (url: string) =>
    `<figure><img src="${url}" alt="${escapeAttr(altText)}" />${captionHtml}</figure>`;

  const remaining = imageUrls.slice(1);
  const remainingCloses = paragraphCloses.slice(1);

  if (remainingCloses.length === 0) {
    insertSet.set(paragraphCloses[0], imageUrls.map(makeFigure).join("\n"));
  } else {
    insertSet.set(paragraphCloses[0], makeFigure(imageUrls[0]));
    const N = remainingCloses.length;
    const M = Math.min(remaining.length, N);
    for (let k = 0; k < M; k++) {
      const pos = M === N ? k : Math.floor(((k + 1) * N) / (M + 1));
      const closeIdx = remainingCloses[Math.min(N - 1, pos)];
      if (!insertSet.has(closeIdx)) {
        insertSet.set(closeIdx, makeFigure(remaining[k]));
      }
    }
  }

  // Re-assemble.
  const rebuilt: string[] = [];
  parts.forEach((seg, i) => {
    rebuilt.push(seg);
    if (insertSet.has(i)) rebuilt.push(insertSet.get(i)!);
  });
  return rebuilt.join("");
}

function escapeAttr(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

interface AiParaphrase {
  title: string;
  excerpt: string;
  content: string;
  suggestedTags: string[];
}

function stripCodeFence(raw: string): string {
  const trimmed = raw.trim();
  const fenced = trimmed.match(/^```(?:json)?\s*\n?([\s\S]*?)\n?```$/);
  if (fenced) return fenced[1].trim();
  return trimmed;
}

function tryParseAi(raw: string): AiParaphrase | null {
  const tryParseJson = (candidate: string): Record<string, unknown> | null => {
    try {
      const parsed = JSON.parse(candidate);
      if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) {
        return parsed as Record<string, unknown>;
      }
    } catch {
      /* fall through */
    }
    return null;
  };

  const cleaned = stripCodeFence(raw);
  let parsed = tryParseJson(cleaned);
  if (!parsed) {
    const objMatch = cleaned.match(/\{[\s\S]*\}/);
    if (objMatch) parsed = tryParseJson(objMatch[0]);
  }
  if (
    parsed &&
    typeof parsed.title === "string" &&
    typeof parsed.content === "string"
  ) {
    const cleanedTitle = cleanAIShortText(parsed.title) || parsed.title.trim();
    const cleanedExcerpt =
      typeof parsed.excerpt === "string"
        ? cleanAIShortText(parsed.excerpt) || parsed.excerpt.trim()
        : "";
    const cleanedContent = cleanAILongText(parsed.content) || parsed.content.trim();
    return {
      title: cleanedTitle,
      excerpt: cleanedExcerpt,
      content: cleanedContent,
      suggestedTags: Array.isArray(parsed.suggestedTags)
        ? parsed.suggestedTags
            .filter((t: unknown): t is string => typeof t === "string")
            .slice(0, 8)
        : [],
    };
  }
  return null;
}

async function uniqueSlug(base: string): Promise<string> {
  const root = slugify(base).slice(0, 90) || "artikel";
  const existing = await prisma.article.findUnique({
    where: { slug: root },
    select: { id: true },
  });
  if (!existing) return root;
  const suffix = Math.random().toString(36).slice(2, 8);
  return `${root}-${suffix}`;
}

function buildAttribution(
  sourceUrl: string,
  sourceName: string,
  originalTitle: string,
): string {
  const safeTitle = escapeAttr(originalTitle.replace(/[<>"]/g, ""));
  return `<p class="text-sm italic text-txt-muted mt-8 pt-4 border-t border-border">Disarikan dari rilis <a href="${escapeAttr(sourceUrl)}" target="_blank" rel="nofollow noopener">${escapeAttr(sourceName)} — "${safeTitle}"</a>. Versi Lensaplus ditulis ulang oleh tim editorial dengan dukungan AI; fakta dan kutipan tetap mengacu ke publikasi asli.</p>`;
}

export interface ParaphraseInput {
  /** The scraped upstream article. */
  source: ScrapedArticle;
  /** Display name of the source (e.g. "Bank BJB"). */
  sourceName: string;
  /** Owner of the resulting draft. */
  authorId: string;
  authorName: string;
  /** Category the draft will land in. */
  categoryId: string;
  /** Default tags from the NewsSource. */
  defaultTags?: string[];
  /** Optional thumbnail URL captured from the listing card as a fallback hero. */
  listingThumbnail?: string;
  /** Whether to download the hero image. Default true. */
  downloadImage?: boolean;
}

export interface ParaphraseResult {
  articleId: string;
  slug: string;
  title: string;
  /** Tokens reported by callAI(). */
  tokens: number;
  /** AI provider used. */
  provider: string;
  /** Local URL of the downloaded hero image, if any. */
  featuredImage?: string;
  /** Detected language of the upstream source. */
  sourceLang?: string;
}

export async function paraphraseAndCreateDraft(
  input: ParaphraseInput,
): Promise<ParaphraseResult> {
  const { source, sourceName, authorId, categoryId, defaultTags = [] } = input;
  const downloadImage = input.downloadImage ?? true;

  // Photo credit = the real publisher derived from the upstream URL's domain
  // (e.g. https://www.bola.com/... → "Bola"), NOT the configured source name —
  // editors sometimes name a source "Lensaplus", which wrongly credited our
  // own site as the photo source. Falls back to sourceName if the URL can't
  // be parsed into a brand.
  const creditLabel = sourceLabelFromUrl(source.url) ?? sourceName;

  const isEnglish = source.lang === "en";
  const langInstruction = isEnglish
    ? `Sumber dalam Bahasa Inggris — terjemahkan SEKALIGUS parafrase ke Bahasa Indonesia jurnalistik yang baik dan benar.`
    : `Sumber dalam Bahasa Indonesia — parafrase ulang dengan kalimat yang berbeda namun mempertahankan fakta.`;

  const userPrompt = `Anda menulis ulang sebuah artikel berita untuk Lensaplus (media berita digital Bandung dengan fokus bisnis, ekonomi, pemerintahan, dan hukum, plus topik general lain) dengan gaya jurnalistik objektif.

${langInstruction}

ATURAN WAJIB:
- JANGAN menjiplak kalimat sumber. Susun ulang sepenuhnya.
- JANGAN tambahkan klaim yang tidak ada di sumber.
- Pertahankan SEMUA angka, nama, jabatan, dan kutipan langsung dari sumber dengan akurat.
- Lead paragraf wajib menjawab 5W+1H.
- Panjang body: 500-800 kata.
- Hasil HTML rapi: <p>, <h2>, <ul>, <strong> seperlunya.

JUDUL SUMBER: "${source.title}"

ISI SUMBER (${source.wordCount} kata):
"""
${source.contentHtml.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").slice(0, 6_000)}
"""

Format output WAJIB JSON valid (tanpa teks lain di luar JSON):
{
  "title": "judul Lensaplus yang fresh & menarik (50-80 karakter, hindari clickbait)",
  "excerpt": "ringkasan 130-160 karakter dalam Bahasa Indonesia",
  "content": "body artikel HTML 500-800 kata, lead 5W+1H, paragraf rapi",
  "suggestedTags": ["tag1", "tag2", "tag3", "tag4", "tag5"]
}`;

  const ai = await callAI({
    feature: "article_draft",
    userPrompt,
    maxTokens: 2_500,
    temperature: 0.65,
    userId: authorId,
    articleTitle: source.title,
  });

  const parsed = tryParseAi(ai.text);
  if (!parsed) {
    throw new Error(
      `AI did not return parseable JSON for ${source.url}. First 200 chars: ${ai.text.slice(0, 200)}`,
    );
  }

  // Image: download hero (trying candidates in priority order) + body images to /uploads.
  const heroCandidateUrls = Array.from(
    new Set(
      [
        ...(source.heroImageCandidates ??
          (source.heroImageUrl ? [source.heroImageUrl] : [])),
        ...(input.listingThumbnail ? [input.listingThumbnail] : []),
      ].filter((u) => /^https?:\/\//i.test(u)),
    ),
  );

  let featuredImage: string | undefined;
  let downloadedHeroUpstreamUrl: string | undefined;

  if (downloadImage && heroCandidateUrls.length > 0) {
    for (const candidateUrl of heroCandidateUrls) {
      try {
        const dl = await downloadImageToUploads(candidateUrl, {
          title: parsed.title.slice(0, 200),
          caption: parsed.excerpt || source.excerpt,
          credit: creditLabel,
          referer: source.url,
          uploadedBy: authorId,
          uploaderName: input.authorName,
        });
        featuredImage = dl.url;
        downloadedHeroUpstreamUrl = candidateUrl;
        break;
      } catch (err) {
        console.warn(
          `[scraper] hero image download failed (${candidateUrl}):`,
          err instanceof Error ? err.message : String(err),
        );
      }
    }
  } else if (heroCandidateUrls.length > 0) {
    featuredImage = heroCandidateUrls[0];
    downloadedHeroUpstreamUrl = heroCandidateUrls[0];
  }

  // Pull body images from pre-sanitized extraction (preserves lazy data-src/srcset)
  // falling back to contentHtml, excluding whichever URL became the hero image.
  const localBodyImageUrls: string[] = [];
  if (downloadImage) {
    const rawCandidates =
      source.bodyImageUrls && source.bodyImageUrls.length > 0
        ? source.bodyImageUrls
        : extractBodyImageUrls(source.contentHtml, source.url);
    const upstreamBodyImageUrls = rawCandidates
      .filter((u) => !downloadedHeroUpstreamUrl || u !== downloadedHeroUpstreamUrl)
      .slice(0, MAX_BODY_IMAGES);

    for (const upstreamUrl of upstreamBodyImageUrls) {
      try {
        const dl = await downloadImageToUploads(upstreamUrl, {
          title: parsed.title.slice(0, 200),
          caption: parsed.excerpt || source.excerpt,
          credit: creditLabel,
          referer: source.url,
          uploadedBy: authorId,
          uploaderName: input.authorName,
        });
        localBodyImageUrls.push(dl.url);
      } catch (err) {
        console.warn(
          `[scraper] body image download failed (${upstreamUrl}):`,
          err instanceof Error ? err.message : String(err),
        );
      }
    }

    // Last-resort hero promotion: if all hero candidates failed, promote first body image.
    if (!featuredImage && localBodyImageUrls.length > 0) {
      featuredImage = localBodyImageUrls.shift();
    }
  }

  const bodyWithImages = injectImagesIntoBody(
    parsed.content,
    localBodyImageUrls,
    parsed.title,
    creditLabel,
  );
  const attributionHtml = buildAttribution(source.url, creditLabel, source.title);
  const finalContent = sanitizeHtml(bodyWithImages + attributionHtml);

  const slug = await uniqueSlug(parsed.title);

  // Tags: prioritise configured source defaults first, then AI suggestions (capped 8).
  const seenTagSlugs = new Set<string>();
  const allTagNames: string[] = [];
  for (const rawTag of [...defaultTags, ...parsed.suggestedTags]) {
    if (typeof rawTag !== "string") continue;
    const trimmed = rawTag.trim().slice(0, 40);
    if (!trimmed) continue;
    const slug = slugify(trimmed);
    if (!slug || seenTagSlugs.has(slug)) continue;
    seenTagSlugs.add(slug);
    allTagNames.push(trimmed);
    if (allTagNames.length >= 8) break;
  }

  // Safely resolve/create tag IDs without P2002 race collisions
  const resolvedTagIds = await resolveTagIds(allTagNames);
  const tagConnections = resolvedTagIds.map((id) => ({ id }));

  const article = await prisma.article.create({
    data: {
      title: parsed.title.slice(0, 250),
      slug,
      content: finalContent,
      excerpt:
        parsed.excerpt.slice(0, 500) || source.excerpt.slice(0, 500) || null,
      status: "DRAFT",
      isAutoGenerated: true,
      sourceArticleId: null,
      featuredImage: featuredImage || null,
      authorId,
      categoryId,
      tags:
        tagConnections.length > 0 ? { connect: tagConnections } : undefined,
      sources: {
        create: [
          {
            name: creditLabel,
            url: source.url,
          },
        ],
      },
    },
    select: { id: true, slug: true, title: true },
  });

  enqueueSorotanGeneration(article.id);

  return {
    articleId: article.id,
    slug: article.slug,
    title: article.title,
    tokens: ai.totalTokens,
    provider: ai.provider,
    featuredImage,
    sourceLang: source.lang,
  };
}
