import { prisma } from "@/lib/prisma";
import { getStorageDriver } from "@/lib/storage";
import { extractSafeUploadKey } from "@/lib/safe-path";

const SIBLING_VARIANT_EXTENSIONS = [".webp", ".avif"] as const;

async function isUploadPathReferenced(
  localPath: string,
  excludeArticleIds: string[],
  excludeMediaIds: string[],
  checkMediaTable: boolean,
): Promise<boolean> {
  const articleRef = await prisma.article.findFirst({
    where: {
      ...(excludeArticleIds.length > 0 ? { id: { notIn: excludeArticleIds } } : {}),
      OR: [
        { featuredImage: localPath },
        { featuredImage: { endsWith: localPath } },
        { content: { contains: localPath } },
      ],
    },
    select: { id: true },
  });
  if (articleRef) return true;

  if (checkMediaTable) {
    const mediaRef = await prisma.media.findFirst({
      where: {
        ...(excludeMediaIds.length > 0 ? { id: { notIn: excludeMediaIds } } : {}),
        OR: [
          { url: localPath },
          { url: { endsWith: localPath } },
        ],
      },
      select: { id: true },
    });
    if (mediaRef) return true;
  }

  return false;
}

/**
 * Safely delete an uploaded file (and its `.webp` / `.avif` sibling variants
 * generated by `/api/upload`) ONLY when it is no longer referenced by any
 * `Article.featuredImage`, `Article.content`, or `Media.url` row.
 *
 * Returns `true` if the primary file was deleted, `false` if skipped (external
 * URL, invalid key, or still referenced).
 */
export async function deleteUploadIfUnreferenced(
  imageUrl: string | null | undefined,
  opts: {
    excludeArticleIds?: string[];
    excludeMediaIds?: string[];
    checkMediaTable?: boolean;
  } = {},
): Promise<boolean> {
  const key = extractSafeUploadKey(imageUrl);
  if (!key) return false;

  const excludeArticleIds = opts.excludeArticleIds ?? [];
  const excludeMediaIds = opts.excludeMediaIds ?? [];
  const checkMediaTable = opts.checkMediaTable ?? true;
  const localPath = `/uploads/${key}`;

  const referenced = await isUploadPathReferenced(
    localPath,
    excludeArticleIds,
    excludeMediaIds,
    checkMediaTable,
  );
  if (referenced) return false;

  const storage = getStorageDriver();
  await storage.delete(key).catch(() => {});

  // /api/upload emits `.webp` and `.avif` variants sharing the same stem for
  // primary `.jpg`/`.jpeg`/`.png` uploads. Remove each unreferenced sibling too.
  if (/\.(jpe?g|png)$/i.test(key)) {
    const stem = key.replace(/\.[^/.]+$/, "");
    for (const ext of SIBLING_VARIANT_EXTENSIONS) {
      const variantKey = `${stem}${ext}`;
      const variantPath = `/uploads/${variantKey}`;
      const variantReferenced = await isUploadPathReferenced(
        variantPath,
        excludeArticleIds,
        excludeMediaIds,
        checkMediaTable,
      );
      if (!variantReferenced) {
        await storage.delete(variantKey).catch(() => {});
      }
    }
  }

  return true;
}
