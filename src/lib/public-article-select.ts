export type PublicArticleCardRecord = Prisma.ArticleGetPayload<{
  select: typeof PUBLIC_ARTICLE_CARD_SELECT;
}>;

export type HomeTrendingArticleRecord = Prisma.ArticleGetPayload<{
  select: typeof HOME_TRENDING_ARTICLE_SELECT;
}>;

export interface PublicArticleCardDTO {
  id: string;
  title: string;
  slug: string;
  excerpt: string | null;
  featuredImage: string | null;
  publishedAt: string | null;
  readTime: number | null;
  viewCount: number;
  verificationLabel: string;
  author: {
    name: string;
    avatar: string | null;
  };
  category: {
    name: string;
    slug: string;
  };
}

/**
 * Explicit whitelist DTO serializer for passing article cards from RSC
 * boundaries into Client Components. Never leaks extra DB columns.
 */
export function serializePublicArticleCard(
  article: PublicArticleCardRecord,
): PublicArticleCardDTO {
  return {
    id: article.id,
    title: article.title,
    slug: article.slug,
    excerpt: article.excerpt ?? null,
    featuredImage: article.featuredImage ?? null,
    publishedAt: article.publishedAt
      ? new Date(article.publishedAt).toISOString()
      : null,
    readTime: article.readTime ?? null,
    viewCount: article.viewCount ?? 0,
    verificationLabel: article.verificationLabel,
    author: {
      name: article.author.name,
      avatar: article.author.avatar ?? null,
    },
    category: {
      name: article.category.name,
      slug: article.category.slug,
    },
  };
}

export function serializePublicArticleCards(
  articles: PublicArticleCardRecord[],
): PublicArticleCardDTO[] {
  return articles.map(serializePublicArticleCard);
}
